export function getGuide(slug: string): Guide | undefined {
  return GUIDES.find((item) => item.slug === slug);
}

export function searchGuides(query: string): Guide[] {
  const q = query.trim().toLocaleLowerCase("es");
  if (!q) return GUIDES;
  return GUIDES.filter((item) => {
    const hay = [item.name, item.summary, item.detail, item.slug, ...item.aka].join(" ").toLocaleLowerCase("es");
    return q.split(/\s+/).every((part) => hay.includes(part));
  });
}

const LIVE_HINTS: { slug: string; words: string[] }[] = GUIDES.map((item) => ({
  slug: item.slug,
  words: [item.name, item.slug, ...item.aka].map((word) => word.toLocaleLowerCase("es")),
}));

export function matchGuideSlug(text: string): string | null {
  const hay = text.toLocaleLowerCase("es");
  let best: { slug: string; score: number } | null = null;
  for (const hint of LIVE_HINTS) {
    let score = 0;
    for (const word of hint.words) {
      if (word.length >= 4 && hay.includes(word)) score += word.length;
    }
    if (score > 0 && (!best || score > best.score)) best = { slug: hint.slug, score };
  }
  return best?.slug ?? null;
}
